# 2. TIER-1: RAPID FIELD SCREENING LOGIC (NON-TECHNICAL)
# ==============================================================================
def tier1_rapid_screening(slope_type, veg_cover, visual_cracks, water_seepage, rain_condition):
    score = 0

    # 1. Slope Category
    if slope_type == "Flat / Gentle Slope (<15°)": score += 5
    elif slope_type == "Moderate Slope (15°-35°)": score += 20
    elif slope_type == "Steep Slope / Cliff (>35°)": score += 35

    # 2. Vegetation
    if veg_cover == "Dense Trees / Vegetation": score -= 10
    elif veg_cover == "Sparse Grass / Shrubs": score += 10
    elif veg_cover == "Bare Soil / Barren Rock": score += 20

    # 3. Visual Signs
    if visual_cracks == "Yes": score += 25
    if water_seepage == "Yes": score += 15

    # 4. Triggering Factor (Rainfall)
    if rain_condition == "Heavy / Continuous Rain": score += 25
    elif rain_condition == "Moderate Rain": score += 15

    score = max(0, min(100, score))

    inputs_dict = {
        "Slope Geometry": slope_type,
        "Vegetation Cover": veg_cover,
        "Visible Ground Cracks": visual_cracks,
        "Water Seepage / Wetness": water_seepage,
        "Rainfall Condition": rain_condition,
        "Landslide Risk Score": f"{score} / 100"
    }

    if score < 35:
        status = f"🟢 Low Hazard Risk (Score: {score}/100)"
        recs = (
            "• Site is currently STABLE under observation.\n"
            "• Keep surface drainage channels clear of debris.\n"
            "• Avoid deforestation or cutting vegetation along slope toe."
        )
    elif score < 65:
        status = f"🟡 Moderate Hazard Risk (Score: {score}/100)"
        recs = (
            "• CAUTION: Slope is vulnerable during active precipitation.\n"
            "• Monitor tension cracks and water seepage points daily.\n"
            "• Clear drainage outlets to avoid water accumulation behind slope.\n"
            "• Prepare field evacuation protocol if rain persists."
        )
    else:
        status = f"🔴 High Hazard Risk (Score: {score}/100)"
        recs = (
            "⚠️ HIGH DANGER / IMMINENT FAILURE HAZARD!\n"
            "• Immediately evacuate toe and crest zones.\n"
            "• Restrict traffic and infrastructure access near slope.\n"
            "• Notify local disaster management & response authorities instantly."
        )

    pdf_path = generate_pdf_report("Tier-1 Rapid Screening", "Field_Screening", status, recs, inputs_dict)
    return status, recs, pdf_path

