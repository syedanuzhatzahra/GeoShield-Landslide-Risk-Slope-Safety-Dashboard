# 3. TIER-2: ADVANCED GEOTECHNICAL ANALYSIS LOGIC (ENGINEERS)
# ==============================================================================
def tier2_geotechnical_analysis(mat_type, H, beta_deg, surcharge, c, phi_deg, gamma, ru, rmr, joint_orientation):
    inputs_dict = {
        "Material Classification": mat_type,
        "Slope Height (H)": f"{H} m",
        "Slope Angle (β)": f"{beta_deg}°",
        "Surcharge Load (q)": f"{surcharge} kPa"
    }

    if mat_type == "Soil Slope":
        try:
            beta = math.radians(beta_deg)
            phi = math.radians(phi_deg)

            # Limit Equilibrium Planar Failure Equation with Surcharge Load (q) & Slope Height (H)
            W = 0.5 * gamma * (H**2) / math.tan(beta)  # Mass Weight Approximation
            N = (W + surcharge) * math.cos(beta)       # Normal Force
            T = (W + surcharge) * math.sin(beta)       # Driving Shear Force

            pore_pressure = ru * gamma * H
            effective_N = max(0, N - pore_pressure)

            resisting_force = (c * (H / math.sin(beta))) + (effective_N * math.tan(phi))
            driving_force = T

            FS = round(resisting_force / driving_force, 3) if driving_force > 0 else 0.0

            inputs_dict.update({
                "Cohesion (c')": f"{c} kPa",
                "Internal Friction Angle (ϕ')": f"{phi_deg}°",
                "Soil Unit Weight (γ)": f"{gamma} kN/m³",
                "Pore Water Pressure Ratio (ru)": ru,
                "Factor of Safety (FS)": FS
            })

            if FS > 1.5:
                status = f"🟢 Stable Soil Slope (Factor of Safety, FS = {FS})"
                recs = (
                    "• Slope is geotechnically STABLE under current static loads.\n"
                    "• Maintain current drainage system and routine inspections."
                )
            elif 1.0 <= FS <= 1.5:
                status = f"🟡 Marginally Stable Soil Slope (Factor of Safety, FS = {FS})"
                recs = (
                    "• MARGINALLY STABLE: Susceptible to failure during heavy rain/seismic events.\n"
                    "• Engineering Action 1: Install sub-surface horizontal drain pipes.\n"
                    "• Engineering Action 2: Apply bio-engineering solutions (e.g., Vetiver grass planting).\n"
                    "• Avoid adding further surcharge or building structures near crest."
                )
            else:
                status = f"🔴 Critical / Unstable Soil Slope (Factor of Safety, FS = {FS})"
                recs = (
                    "⚠️ CRITICAL STABILITY FAILURE (FS < 1.0)!\n"
                    "• Engineering Intervention 1: Construct retaining structures (Gabion walls / MSE walls).\n"
                    "• Engineering Intervention 2: Install structural soil nails or tie-back anchor bolts.\n"
                    "• Immediate shotcrete sealant application to prevent water infiltration."
                )

        except Exception as err:
            return "Calculation Error", str(err), None

    else:
        # Rock Slope Stability (RMR Adjustment for Discontinuity Dip Orientation)
        joint_penalty = -25 if joint_orientation == "Adverse (Dipping Out of Slope)" else (-5 if joint_orientation == "Fair / Random" else 0)
        adjusted_rmr = rmr + joint_penalty

        inputs_dict.update({
            "Basic RMR Score": rmr,
            "Discontinuity / Joint Condition": joint_orientation,
            "Adjusted Rock Mass Rating": adjusted_rmr
        })

        if adjusted_rmr > 60:
            status = f"🟢 Good Rock Mass - Class I/II (Adjusted RMR = {adjusted_rmr})"
            recs = (
                "• Rock mass is structurally STABLE.\n"
                "• Install spot rock bolting for isolated loose blocks."
            )
        elif 40 <= adjusted_rmr <= 60:
            status = f"🟡 Fair Rock Mass - Class III (Adjusted RMR = {adjusted_rmr})"
            recs = (
                "• MODERATE RISK: Potential Planar/Wedge failure along joint sets.\n"
                "• Engineering Action 1: Install systematic pattern rock bolts.\n"
                "• Engineering Action 2: Apply shotcrete reinforced with wire mesh mesh."
            )
        else:
            status = f"🔴 Poor Rock Mass - Class IV/V (Adjusted RMR = {adjusted_rmr})"
            recs = (
                "⚠️ HIGH ROCKFALL / TOPPLING FAILURE RISK!\n"
                "• Engineering Action 1: Install heavy cable anchors and catch fencing.\n"
                "• Engineering Action 2: Drill horizontal weep holes to relieve groundwater head.\n"
                "• Apply heavy wire netting along cliff face."
            )

    pdf_path = generate_pdf_report("Tier-2 Geotechnical Analysis", "Geotechnical_Analysis", status, recs, inputs_dict)
    return status, recs, pdf_path

